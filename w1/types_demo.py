print("float('1.75') * 2 =", float("1.75") * 2)
print("str(18) + '岁' =", str(18) + "岁")
print("bool('') =", bool(""))
print("bool('0') =", bool("0"))
print("bool(0) =", bool(0))
print("bool(1) =", bool(1))